import { sql } from "drizzle-orm";
import {
  bigint,
  boolean,
  check,
  date,
  index,
  integer,
  pgTable,
  primaryKey,
  text,
  timestamp,
  uuid,
} from "drizzle-orm/pg-core";

const timestamps = {
  createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
};

export const users = pgTable("users", {
  id: uuid("id").primaryKey().defaultRandom(),
  githubId: bigint("github_id", { mode: "number" }).notNull().unique(),
  username: text("username").notNull().unique(),
  name: text("name"),
  avatarUrl: text("avatar_url"),

  // Privacy settings
  showPresence: boolean("show_presence").notNull().default(true),
  showLanguage: boolean("show_language").notNull().default(true),

  // Presence: online = last_seen_at within the window AND not signed off since.
  lastSeenAt: timestamp("last_seen_at", { withTimezone: true }),
  offlineAt: timestamp("offline_at", { withTimezone: true }),
  presenceLanguage: text("presence_language"),
  presenceEditor: text("presence_editor"),

  // Moderation (ADR 0007): set by the maintainer to keep an account off the leaderboard. The
  // reason is a private note; the user only sees that they're hidden.
  leaderboardHiddenAt: timestamp("leaderboard_hidden_at", { withTimezone: true }),
  leaderboardHiddenReason: text("leaderboard_hidden_reason"),

  ...timestamps,
  updatedAt: timestamp("updated_at", { withTimezone: true })
    .notNull()
    .defaultNow()
    .$onUpdate(() => new Date()),
});

/** Browser login sessions. Only the SHA-256 of the cookie token is stored. */
export const authSessions = pgTable(
  "auth_sessions",
  {
    id: text("id").primaryKey(),
    userId: uuid("user_id")
      .notNull()
      .references(() => users.id, { onDelete: "cascade" }),
    expiresAt: timestamp("expires_at", { withTimezone: true }).notNull(),
    ...timestamps,
  },
  (t) => [index("auth_sessions_user_idx").on(t.userId)],
);

/** Editor API keys. Only the SHA-256 is stored; the plaintext is shown once at creation. */
export const apiKeys = pgTable(
  "api_keys",
  {
    id: uuid("id").primaryKey().defaultRandom(),
    userId: uuid("user_id")
      .notNull()
      .references(() => users.id, { onDelete: "cascade" }),
    name: text("name").notNull(),
    keyHash: text("key_hash").notNull().unique(),
    /** First characters of the key, for display ("fy_ab12…"). */
    keyPrefix: text("key_prefix").notNull(),
    lastUsedAt: timestamp("last_used_at", { withTimezone: true }),
    revokedAt: timestamp("revoked_at", { withTimezone: true }),
    ...timestamps,
  },
  (t) => [index("api_keys_user_idx").on(t.userId)],
);

/** One closed coding session. The id is generated by the client so retries are idempotent. */
export const codingSessions = pgTable(
  "coding_sessions",
  {
    id: uuid("id").primaryKey(),
    userId: uuid("user_id")
      .notNull()
      .references(() => users.id, { onDelete: "cascade" }),
    startedAt: timestamp("started_at", { withTimezone: true }).notNull(),
    endedAt: timestamp("ended_at", { withTimezone: true }).notNull(),
    durationSeconds: integer("duration_seconds").notNull(),
    language: text("language").notNull(),
    project: text("project"),
    editor: text("editor").notNull(),
    linesAdded: integer("lines_added").notNull().default(0),
    linesRemoved: integer("lines_removed").notNull().default(0),
    receivedAt: timestamp("received_at", { withTimezone: true }).notNull().defaultNow(),
  },
  (t) => [
    index("coding_sessions_user_started_idx").on(t.userId, t.startedAt),
    index("coding_sessions_started_idx").on(t.startedAt),
    check("coding_sessions_duration_positive", sql`${t.durationSeconds} > 0`),
    check("coding_sessions_end_after_start", sql`${t.endedAt} > ${t.startedAt}`),
  ],
);

/**
 * Seconds coded per user, UTC day (of each session's start) and language: a rollup of
 * `coding_sessions` that keeps leaderboard queries fast as sessions pile up (ADR 0006).
 * Maintained by `ingestSessions` in the same transaction as the sessions themselves, so it always
 * equals the sum of `coding_sessions`; `rebuildDailyStats` recomputes it from scratch.
 */
export const dailyStats = pgTable(
  "daily_stats",
  {
    userId: uuid("user_id")
      .notNull()
      .references(() => users.id, { onDelete: "cascade" }),
    day: date("day", { mode: "string" }).notNull(),
    language: text("language").notNull(),
    seconds: integer("seconds").notNull(),
  },
  (t) => [
    primaryKey({ columns: [t.userId, t.day, t.language] }),
    index("daily_stats_day_idx").on(t.day),
  ],
);

export type User = typeof users.$inferSelect;
export type CodingSession = typeof codingSessions.$inferSelect;
